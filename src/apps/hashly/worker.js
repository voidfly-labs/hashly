import {
  adler32,
  blake2b,
  blake2s,
  blake3,
  createAdler32,
  createBLAKE2b,
  createBLAKE2s,
  createBLAKE3,
  createKeccak,
  createMD4,
  createMD5,
  createRIPEMD160,
  createSHA1,
  createSHA3,
  createSHA224,
  createSHA256,
  createSHA384,
  createSHA512,
  createSM3,
  createWhirlpool,
  createXXHash3,
  createXXHash32,
  createXXHash64,
  createXXHash128,
  keccak,
  md4,
  md5,
  ripemd160,
  sha1,
  sha3,
  sha224,
  sha256,
  sha384,
  sha512,
  sm3,
  whirlpool,
  xxhash3,
  xxhash32,
  xxhash64,
  xxhash128,
} from 'hash-wasm';

import { md2Engine } from '~core/features/hashing/workers/engines/md2.js';
import { ripemdEngine } from '~core/features/hashing/workers/engines/ripemd.js';
import { wasmEngine } from '~core/features/hashing/workers/engines/wasm.js';
import { initHasherServer } from '~core/features/hashing/workers/hasher-server.js';

// Algorithms that take a size: `fn(bytes, bits)` / `createFn(bits)`.
const sized = (fn, createFn, bits) => wasmEngine({ fn: (bytes) => fn(bytes, bits), createFn: () => createFn(bits) });

initHasherServer({
  MD2: md2Engine,
  MD4: wasmEngine({ fn: md4, createFn: createMD4 }),
  MD5: wasmEngine({ fn: md5, createFn: createMD5 }),
  'SHA-1': wasmEngine({ fn: sha1, createFn: createSHA1 }),
  'SHA-224': wasmEngine({ fn: sha224, createFn: createSHA224 }),
  'SHA-256': wasmEngine({ fn: sha256, createFn: createSHA256 }),
  'SHA-384': wasmEngine({ fn: sha384, createFn: createSHA384 }),
  'SHA-512': wasmEngine({ fn: sha512, createFn: createSHA512 }),
  'SHA3-224': sized(sha3, createSHA3, 224),
  'SHA3-256': sized(sha3, createSHA3, 256),
  'SHA3-384': sized(sha3, createSHA3, 384),
  'SHA3-512': sized(sha3, createSHA3, 512),
  'BLAKE2b-256': sized(blake2b, createBLAKE2b, 256),
  'BLAKE2b-512': sized(blake2b, createBLAKE2b, 512),
  'BLAKE2s-128': sized(blake2s, createBLAKE2s, 128),
  'BLAKE2s-256': sized(blake2s, createBLAKE2s, 256),
  'BLAKE3-256': sized(blake3, createBLAKE3, 256),
  'BLAKE3-512': sized(blake3, createBLAKE3, 512),
  'Keccak-224': sized(keccak, createKeccak, 224),
  'Keccak-256': sized(keccak, createKeccak, 256),
  'Keccak-384': sized(keccak, createKeccak, 384),
  'Keccak-512': sized(keccak, createKeccak, 512),
  'RIPEMD-128': ripemdEngine(128),
  'RIPEMD-160': wasmEngine({ fn: ripemd160, createFn: createRIPEMD160 }),
  'RIPEMD-256': ripemdEngine(256),
  'RIPEMD-320': ripemdEngine(320),
  XXH32: wasmEngine({ fn: xxhash32, createFn: createXXHash32 }),
  XXH64: wasmEngine({ fn: xxhash64, createFn: createXXHash64 }),
  XXH3: wasmEngine({ fn: xxhash3, createFn: createXXHash3 }),
  XXH128: wasmEngine({ fn: xxhash128, createFn: createXXHash128 }),
  'Adler-32': wasmEngine({ fn: adler32, createFn: createAdler32 }),
  SM3: wasmEngine({ fn: sm3, createFn: createSM3 }),
  Whirlpool: wasmEngine({ fn: whirlpool, createFn: createWhirlpool }),
});
